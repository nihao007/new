/* get offset value of member in type struct */
#define OFFSET_OF(type, member)  (unsigned int)(&(((type *)0)->member))

/* IOCMG_BASE_ADDR: 0x147F0000 */
/* IOCMG_PIN_MUX(32bit) = ADDRESS_OFFSET(31~16) | DEFAULT_VALUE(15~4) | FUNC_NUM(3~0bit) */
